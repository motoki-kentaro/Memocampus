// Keep the canonical JSON usable by Rust and by ordinary browser ES modules.
import { readFileSync, writeFileSync } from "node:fs";
const input = new URL("../extension/policy-builtins.json", import.meta.url);
const output = new URL("../extension/policy-builtins.js", import.meta.url);
const source = "// Generated by scripts/generate-policy-builtins.mjs; do not edit.\nexport default "
  + JSON.stringify(JSON.parse(readFileSync(input, "utf8")), null, 2) + ";\n";
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== source) throw new Error("Regenerate policy-builtins.js");
} else writeFileSync(output, source);
